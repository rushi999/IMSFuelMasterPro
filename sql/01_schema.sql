CREATE OR REPLACE TRIGGER TRG_UNIT_MASTER_ID
BEFORE INSERT ON UNIT_MASTER
FOR EACH ROW
BEGIN
   IF :NEW.UNIT_ID IS NULL THEN
      SELECT SEQ_UNIT_MASTER.NEXTVAL
      INTO :NEW.UNIT_ID
      FROM DUAL;
   END IF;
END;
