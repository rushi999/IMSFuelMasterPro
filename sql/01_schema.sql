-- ── TANK MASTER ────────────────────────────────────────────
CREATE TABLE TANK_MASTER (
  TANK_ID       NUMBER PRIMARY KEY,
  TANK_CODE     VARCHAR2(20)  NOT NULL UNIQUE,
  TANK_NAME     VARCHAR2(50)  NOT NULL,
  FUEL_TYPE     VARCHAR2(10)  CHECK (FUEL_TYPE IN ('DIESEL','PETROL')),
  CAPACITY      NUMBER(10,2)  DEFAULT 20000,
  CURRENT_LEVEL NUMBER(10,2)  DEFAULT 0,
  LOW_THRESHOLD  NUMBER(5,2)  DEFAULT 25,
  VERY_LOW_THRESHOLD NUMBER(5,2) DEFAULT 12,
  LAST_REFILL_DT DATE,
  LAST_REFILL_QTY NUMBER(10,2),
  IS_ACTIVE     CHAR(1)       DEFAULT 'Y'
);

-- ── FUEL ENTRY ─────────────────────────────────────────────
CREATE TABLE FUEL_ENTRY (
  ENTRY_ID      NUMBER PRIMARY KEY,
  REQ_NO        VARCHAR2(20),
  ENTRY_CATEGORY VARCHAR2(20) NOT NULL CHECK (ENTRY_CATEGORY IN ('BARC','UNIT','LOOSE')),
  VEHICLE_NO    VARCHAR2(20),
  VEHICLE_TYPE  VARCHAR2(30),
  FUEL_TYPE     VARCHAR2(10) NOT NULL CHECK (FUEL_TYPE IN ('DIESEL','PETROL')),
  TANK_ID       NUMBER REFERENCES TANK_MASTER(TANK_ID),
  QTY_ISSUED    NUMBER(10,2) NOT NULL,
  RATE_PER_LITRE NUMBER(8,2),
  AMOUNT        NUMBER(10,2),
  DRIVER_NAME   VARCHAR2(100),
  DRIVER_BADGE  VARCHAR2(20),
  DRIVER_CONTACT VARCHAR2(15),
  DEPARTMENT    VARCHAR2(100),
  ORG_NAME      VARCHAR2(100),
  UNIT_ID       NUMBER REFERENCES UNIT_MASTER(UNIT_ID),
  PURPOSE       VARCHAR2(200),
  SUPPLY_TYPE   VARCHAR2(30),
  PREV_ODOMETER NUMBER(10),
  CURR_ODOMETER NUMBER(10),
  DISTANCE_KM   NUMBER(8,2),
  AVG_MILEAGE   NUMBER(6,2),
  INDENT_NO     VARCHAR2(50),
  AUTH_OFFICER  VARCHAR2(100),
  ISSUED_BY     VARCHAR2(100),
  ENTRY_DATE    DATE DEFAULT SYSDATE,
  ENTRY_TIME    VARCHAR2(10),
  REMARKS       VARCHAR2(500),
  CREATED_BY    NUMBER REFERENCES USERS(USER_ID),
  CREATED_DT    DATE DEFAULT SYSDATE
);

CREATE OR REPLACE TRIGGER TRG_FUEL_ENTRY_REQNO
BEFORE INSERT ON FUEL_ENTRY
FOR EACH ROW
BEGIN

  IF :NEW.ENTRY_ID IS NULL THEN
    SELECT SEQ_FUEL_ENTRY.NEXTVAL
    INTO :NEW.ENTRY_ID
    FROM DUAL;
  END IF;

  :NEW.REQ_NO :=
      'REQ-' ||
      TO_CHAR(SYSDATE, 'YYYY') ||
      '-' ||
      LPAD(:NEW.ENTRY_ID, 4, '0');

END;
