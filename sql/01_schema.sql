-- ── VIEWS ──────────────────────────────────────────────────
CREATE OR REPLACE VIEW V_DAILY_REPORT AS
SELECT
  E.ENTRY_ID, E.REQ_NO, E.VEHICLE_NO, E.ENTRY_CATEGORY,
  E.FUEL_TYPE, E.QTY_ISSUED, E.PREV_ODOMETER, E.CURR_ODOMETER,
  E.DISTANCE_KM, E.AVG_MILEAGE, E.DRIVER_NAME,
  E.ISSUED_BY, E.AUTH_OFFICER, E.ENTRY_DATE, E.PURPOSE,
  E.ORG_NAME, E.SUPPLY_TYPE
FROM FUEL_ENTRY E
ORDER BY E.ENTRY_DATE DESC, E.ENTRY_ID DESC;

CREATE OR REPLACE VIEW V_RCAV_MONTHLY AS
SELECT
  E.VEHICLE_NO,
  B.MAKE || ' ' || B.MODEL AS VEHICLE_MODEL,
  NVL(B.DEPARTMENT, E.ORG_NAME) AS DEPARTMENT,
  MAX(E.DRIVER_NAME) AS DRIVER_NAME,
  MIN(E.PREV_ODOMETER) AS OPEN_KM,
  MAX(E.CURR_ODOMETER) AS CLOSE_KM,
  MAX(E.CURR_ODOMETER) - MIN(E.PREV_ODOMETER) AS TOTAL_KM,
  SUM(CASE WHEN E.FUEL_TYPE='DIESEL' THEN E.QTY_ISSUED ELSE 0 END) AS DIESEL_LITRES,
  SUM(CASE WHEN E.FUEL_TYPE='PETROL' THEN E.QTY_ISSUED ELSE 0 END) AS PETROL_LITRES,
  SUM(E.QTY_ISSUED) AS TOTAL_FUEL,
  ROUND((MAX(E.CURR_ODOMETER) - MIN(E.PREV_ODOMETER)) / NULLIF(SUM(E.QTY_ISSUED),0), 2) AS AVG_MILEAGE,
  TRUNC(E.ENTRY_DATE,'MM') AS REPORT_MONTH
FROM FUEL_ENTRY E
LEFT JOIN BARC_VEHICLE_MASTER B ON E.VEHICLE_NO = B.VEHICLE_NO
WHERE E.VEHICLE_NO IS NOT NULL
  AND E.PREV_ODOMETER IS NOT NULL
GROUP BY E.VEHICLE_NO, B.MAKE, B.MODEL, NVL(B.DEPARTMENT, E.ORG_NAME), TRUNC(E.ENTRY_DATE,'MM');

CREATE OR REPLACE VIEW V_TANK_STATUS AS
SELECT
  T.TANK_ID, T.TANK_CODE, T.TANK_NAME, T.FUEL_TYPE,
  T.CAPACITY, T.CURRENT_LEVEL,
  ROUND((T.CURRENT_LEVEL / T.CAPACITY) * 100, 2) AS PCT_FULL,
  CASE
    WHEN (T.CURRENT_LEVEL / T.CAPACITY) * 100 > T.LOW_THRESHOLD THEN 'Normal'
    WHEN (T.CURRENT_LEVEL / T.CAPACITY) * 100 > T.VERY_LOW_THRESHOLD THEN 'Low'
    ELSE 'Very Low'
  END AS STATUS,
  T.LAST_REFILL_DT
FROM TANK_MASTER T
WHERE T.IS_ACTIVE = 'Y';

-- ── STORED PROCEDURE: ISSUE FUEL ──────────────────────────
CREATE OR REPLACE PROCEDURE SP_ISSUE_FUEL(
  p_entry_category IN VARCHAR2,
  p_vehicle_no     IN VARCHAR2,
  p_fuel_type      IN VARCHAR2,
  p_qty_issued     IN NUMBER,
  p_driver_name    IN VARCHAR2,
  p_department     IN VARCHAR2,
  p_prev_odometer  IN NUMBER,
  p_curr_odometer  IN NUMBER,
  p_purpose        IN VARCHAR2,
  p_auth_officer   IN VARCHAR2,
  p_issued_by      IN VARCHAR2,
  p_entry_date     IN DATE,
  p_created_by     IN NUMBER,
  p_entry_id      OUT NUMBER,
  p_status        OUT VARCHAR2
) AS
  v_tank_id     NUMBER;
  v_level_before NUMBER;
  v_level_after  NUMBER;
  v_distance     NUMBER;
  v_mileage      NUMBER;
  v_rate         NUMBER;
BEGIN
  -- Get tank
  SELECT TANK_ID, CURRENT_LEVEL INTO v_tank_id, v_level_before
  FROM TANK_MASTER
  WHERE FUEL_TYPE = UPPER(p_fuel_type) AND IS_ACTIVE = 'Y'
    AND CURRENT_LEVEL >= p_qty_issued
    AND ROWNUM = 1;

  -- Check sufficient stock
  IF v_level_before < p_qty_issued THEN
    p_status := 'ERROR: Insufficient fuel in tank';
    RETURN;
  END IF;

  -- Calculate fields
  v_distance := NVL(p_curr_odometer,0) - NVL(p_prev_odometer,0);
  IF v_distance > 0 AND p_qty_issued > 0 THEN
    v_mileage := ROUND(v_distance / p_qty_issued, 2);
  END IF;
IF UPPER(p_fuel_type) = 'PETROL' THEN
   v_rate := 105.40;
ELSE
   v_rate := 93.80;
END IF;

  -- Insert entry
  SELECT SEQ_FUEL_ENTRY.NEXTVAL INTO p_entry_id FROM DUAL;

  INSERT INTO FUEL_ENTRY (
    ENTRY_ID, ENTRY_CATEGORY, VEHICLE_NO, FUEL_TYPE, TANK_ID,
    QTY_ISSUED, RATE_PER_LITRE, AMOUNT, DRIVER_NAME, DEPARTMENT,
    PURPOSE, PREV_ODOMETER, CURR_ODOMETER, DISTANCE_KM, AVG_MILEAGE,
    AUTH_OFFICER, ISSUED_BY, ENTRY_DATE, CREATED_BY
  ) VALUES (
    p_entry_id, p_entry_category, UPPER(p_vehicle_no), UPPER(p_fuel_type), v_tank_id,
    p_qty_issued, v_rate, ROUND(p_qty_issued * v_rate, 2), p_driver_name, p_department,
    p_purpose, p_prev_odometer, p_curr_odometer, v_distance, v_mileage,
    p_auth_officer, p_issued_by, NVL(p_entry_date, SYSDATE), p_created_by
  );

  -- Update tank level
  v_level_after := v_level_before - p_qty_issued;
  UPDATE TANK_MASTER SET CURRENT_LEVEL = v_level_after WHERE TANK_ID = v_tank_id;

  -- Log transaction
  INSERT INTO TANK_TRANSACTION (TANK_ID, TXN_TYPE, QUANTITY, LEVEL_BEFORE, LEVEL_AFTER, ENTRY_ID)
  VALUES (v_tank_id, 'ISSUE', p_qty_issued, v_level_before, v_level_after, p_entry_id);

  COMMIT;
  p_status := 'SUCCESS';

EXCEPTION
  WHEN NO_DATA_FOUND THEN
    p_status := 'ERROR: No active tank found with sufficient fuel for ' || p_fuel_type;
  WHEN OTHERS THEN
    ROLLBACK;
    p_status := 'ERROR: ' || SQLERRM;
END SP_ISSUE_FUEL;
