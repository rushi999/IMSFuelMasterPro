-- Drop sequences and tables if they exist (for re-run safety)
BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
    'FUEL_ENTRY','BARC_VEHICLE_MASTER','UNIT_MASTER','TANK_MASTER',
    'TANK_TRANSACTION','DAILY_REPORT','RCAV_REPORT','USERS'
  )) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
  END LOOP;
END;
/
BEGIN
  FOR s IN (SELECT sequence_name FROM user_sequences WHERE sequence_name IN (
    'SEQ_FUEL_ENTRY','SEQ_UNIT_MASTER','SEQ_TANK_TXN','SEQ_USER'
  )) LOOP
    EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
  END LOOP;
END;
/

-- ── SEQUENCES ──────────────────────────────────────────────
CREATE SEQUENCE SEQ_FUEL_ENTRY  START WITH 841 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_UNIT_MASTER START WITH 1   INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_TANK_TXN    START WITH 1   INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_USER        START WITH 1   INCREMENT BY 1 NOCACHE;

-- ── USERS TABLE ────────────────────────────────────────────
CREATE TABLE USERS (
  USER_ID       NUMBER PRIMARY KEY,
  USERNAME      VARCHAR2(50)  NOT NULL UNIQUE,
  PASSWORD_HASH VARCHAR2(64)  NOT NULL,
  FULL_NAME     VARCHAR2(100) NOT NULL,
  DESIGNATION   VARCHAR2(100),
  ROLE          VARCHAR2(20)  DEFAULT 'OPERATOR' CHECK (ROLE IN ('ADMIN','OPERATOR','VIEWER')),
  IS_ACTIVE     CHAR(1)       DEFAULT 'Y',
  CREATED_DT    DATE          DEFAULT SYSDATE
);

