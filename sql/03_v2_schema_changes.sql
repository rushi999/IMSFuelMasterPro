-- ── NEW SEQUENCES ──────────────────────────────────────────
BEGIN
  FOR s IN (SELECT sequence_name FROM user_sequences WHERE sequence_name IN (
    'SEQ_VEHICLE_MASTER','SEQ_DRIVER_MASTER'
  )) LOOP
    EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
  END LOOP;
END;
/
CREATE SEQUENCE SEQ_VEHICLE_MASTER START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_DRIVER_MASTER  START WITH 1 INCREMENT BY 1 NOCACHE;

-- ── DROP OLD UNIT_MASTER (had vehicle+driver mixed in) ─────
-- CAUTION: Only run if starting fresh. If you have data, migrate first.
