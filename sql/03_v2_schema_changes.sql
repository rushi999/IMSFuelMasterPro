-- ── UNIT MASTER (Organisation only — no vehicle/driver) ────
CREATE TABLE UNIT_MASTER (
  UNIT_ID       NUMBER        DEFAULT SEQ_UNIT_MASTER.NEXTVAL PRIMARY KEY,
  ORG_NAME      VARCHAR2(100) NOT NULL,
  UNIT_CODE     VARCHAR2(20)  UNIQUE,
  UNIT_TYPE     VARCHAR2(50)  DEFAULT 'DAE Unit',
  CONTACT_PERSON VARCHAR2(100),
  DESIGNATION   VARCHAR2(100),
  PHONE_EXT     VARCHAR2(20),
  EMAIL         VARCHAR2(100),
  ADDRESS       VARCHAR2(300),
  STATUS        VARCHAR2(15)  DEFAULT 'Active'
                  CHECK (STATUS IN ('Active','Inactive','Suspended')),
  NOTES         VARCHAR2(500),
  CREATED_DT    DATE          DEFAULT SYSDATE,
  UPDATED_DT    DATE          DEFAULT SYSDATE
);

-- ── VEHICLE MASTER (for Other DAE Units) ───────────────────
CREATE TABLE VEHICLE_MASTER (
  VEHICLE_ID    NUMBER        DEFAULT SEQ_VEHICLE_MASTER.NEXTVAL PRIMARY KEY,
  UNIT_ID       NUMBER        NOT NULL REFERENCES UNIT_MASTER(UNIT_ID),
  VEHICLE_NO    VARCHAR2(20)  NOT NULL UNIQUE,
  VEHICLE_TYPE  VARCHAR2(30),
  MAKE          VARCHAR2(50),
  MODEL         VARCHAR2(50),
  YEAR_MFG      NUMBER(4),
  FUEL_TYPE     VARCHAR2(10)  CHECK (FUEL_TYPE IN ('DIESEL','PETROL')),
  ENGINE_CC     NUMBER(5),
  CHASSIS_NO    VARCHAR2(50),
  STATUS        VARCHAR2(15)  DEFAULT 'Active'
                  CHECK (STATUS IN ('Active','Inactive','Scrapped')),
  NOTES         VARCHAR2(300),
  CREATED_DT    DATE          DEFAULT SYSDATE
);

-- ── DRIVER MASTER (for Other DAE Units) ────────────────────
CREATE TABLE DRIVER_MASTER (
  DRIVER_ID     NUMBER        DEFAULT SEQ_DRIVER_MASTER.NEXTVAL PRIMARY KEY,
  UNIT_ID       NUMBER        NOT NULL REFERENCES UNIT_MASTER(UNIT_ID),
  DRIVER_NAME   VARCHAR2(100) NOT NULL,
  EMPLOYEE_NO   VARCHAR2(30),
  LICENCE_NO    VARCHAR2(30),
  LICENCE_TYPE  VARCHAR2(20),
  LICENCE_EXPIRY DATE,
  CONTACT_NO    VARCHAR2(15),
  ADDRESS       VARCHAR2(300),
  STATUS        VARCHAR2(15)  DEFAULT 'Active'
                  CHECK (STATUS IN ('Active','Inactive','Suspended')),
  NOTES         VARCHAR2(300),
  CREATED_DT    DATE          DEFAULT SYSDATE
);

-- ── TANK MASTER (updated — add refill tracking) ────────────
-- Drop and recreate to add REFILL_LOG table
CREATE TABLE TANK_REFILL_LOG (
  REFILL_ID     NUMBER PRIMARY KEY,
  TANK_ID       NUMBER NOT NULL REFERENCES TANK_MASTER(TANK_ID),
  REFILL_QTY    NUMBER(10,2) NOT NULL,
  LEVEL_BEFORE  NUMBER(10,2),
  LEVEL_AFTER   NUMBER(10,2),
  SUPPLIER      VARCHAR2(100),
  CHALLAN_NO    VARCHAR2(50),
  REFILL_DATE   DATE DEFAULT SYSDATE,
  ENTERED_BY    NUMBER REFERENCES USERS(USER_ID),
  REMARKS       VARCHAR2(300)
);
CREATE SEQUENCE SEQ_REFILL_LOG START WITH 1 INCREMENT BY 1 NOCACHE;

-- ── FUEL_ENTRY table changes ────────────────────────────────
-- Add RCAV_NO column, DRIVER_ID reference, VEHICLE_ID reference
ALTER TABLE FUEL_ENTRY ADD (
  RCAV_NO       VARCHAR2(50),
  DRIVER_ID     NUMBER,
  VEHICLE_ID    NUMBER
);

-- ── INDEXES ────────────────────────────────────────────────
CREATE INDEX IDX_VEHICLE_UNIT   ON VEHICLE_MASTER(UNIT_ID);
CREATE INDEX IDX_VEHICLE_NO_VM  ON VEHICLE_MASTER(VEHICLE_NO);
CREATE INDEX IDX_DRIVER_UNIT    ON DRIVER_MASTER(UNIT_ID);
CREATE INDEX IDX_REFILL_TANK    ON TANK_REFILL_LOG(TANK_ID);
CREATE INDEX IDX_REFILL_DATE    ON TANK_REFILL_LOG(REFILL_DATE);

