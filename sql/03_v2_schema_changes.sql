-- ── VIEW: V_VEHICLE_WITH_UNIT ──────────────────────────────
CREATE OR REPLACE VIEW V_VEHICLE_WITH_UNIT AS
SELECT
  V.VEHICLE_ID, V.VEHICLE_NO, V.VEHICLE_TYPE,
  V.MAKE, V.MODEL, V.YEAR_MFG, V.FUEL_TYPE,
  V.STATUS AS VEHICLE_STATUS,
  U.UNIT_ID, U.ORG_NAME, U.UNIT_CODE
FROM VEHICLE_MASTER V
JOIN UNIT_MASTER U ON V.UNIT_ID = U.UNIT_ID
WHERE V.STATUS = 'Active';

-- ── VIEW: V_DRIVER_WITH_UNIT ───────────────────────────────
CREATE OR REPLACE VIEW V_DRIVER_WITH_UNIT AS
SELECT
  D.DRIVER_ID, D.DRIVER_NAME, D.EMPLOYEE_NO,
  D.LICENCE_NO, D.CONTACT_NO, D.STATUS AS DRIVER_STATUS,
  U.UNIT_ID, U.ORG_NAME, U.UNIT_CODE
FROM DRIVER_MASTER D
JOIN UNIT_MASTER U ON D.UNIT_ID = U.UNIT_ID;

